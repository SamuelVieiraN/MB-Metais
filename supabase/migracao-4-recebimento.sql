-- Migração 4: recebimento de mercadoria por lote, com autorização do gerente e histórico completo.
-- Rode UMA vez no SQL Editor do Supabase (depois da migração 3). Pode repetir sem problema.

create table if not exists public.receipts (
  id          uuid primary key default gen_random_uuid(),
  num         integer generated by default as identity,
  created_at  timestamptz not null default clock_timestamp(),
  updated_at  timestamptz not null default clock_timestamp(),
  user_id     uuid,
  user_name   text not null default '',
  ref         text not null default '',        -- nota fiscal / referência do lote
  supplier    text not null default '',        -- só o gerente vê e edita
  status      text not null default 'pendente'
              check (status in ('pendente', 'concluido', 'concluido_editado', 'excluido')),
  items       jsonb not null default '[]'::jsonb,
  log         jsonb not null default '[]'::jsonb
);
alter table public.receipts enable row level security;
revoke all on public.receipts from authenticated, anon;   -- só pelas funções abaixo

-- uso interno: valida os itens e guarda uma "foto" do nome/código da peça
create or replace function public._receipt_items(p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  it     jsonb;
  v_part public.parts;
  v_rec  integer;
  v_exp  integer;
  v_out  jsonb := '[]'::jsonb;
  v_any  boolean := false;
  v_seen uuid[] := '{}';
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Inclua pelo menos uma peça no recebimento.';
  end if;
  for it in select * from jsonb_array_elements(p_items) loop
    select * into v_part from public.parts where id = (it ->> 'part_id')::uuid;
    if not found then
      raise exception 'Uma das peças do recebimento não existe mais.';
    end if;
    if v_part.id = any (v_seen) then
      raise exception 'A peça "%" aparece duas vezes. Some as quantidades em uma linha só.', v_part.name;
    end if;
    v_seen := v_seen || v_part.id;
    v_rec := (it ->> 'received')::integer;
    v_exp := case when jsonb_typeof(it -> 'expected') = 'number' then (it ->> 'expected')::integer end;
    if v_rec is null or v_rec < 0 or coalesce(v_exp, 0) < 0 then
      raise exception 'As quantidades não podem ser negativas.';
    end if;
    if v_rec > 0 then v_any := true; end if;
    v_out := v_out || jsonb_build_object('part_id', v_part.id, 'name', v_part.name, 'code', v_part.code,
                                         'expected', v_exp, 'received', v_rec);
  end loop;
  if not v_any then
    raise exception 'Informe a quantidade recebida de pelo menos uma peça.';
  end if;
  return v_out;
end;
$$;

-- Qualquer usuário registra o que chegou; fica "pendente" até o gerente autorizar.
create or replace function public.create_receipt(p_ref text, p_items jsonb, p_supplier text default '')
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  me   public.profiles;
  v_id uuid;
begin
  me := public._require_active();
  insert into public.receipts (user_id, user_name, ref, supplier, items, log)
  values (me.id, me.name, btrim(coalesce(p_ref, '')),
          case when me.role = 'gerente' then btrim(coalesce(p_supplier, '')) else '' end,
          public._receipt_items(p_items),
          jsonb_build_array(jsonb_build_object('at', clock_timestamp(), 'by', me.name, 'action', 'criado', 'detail', '')))
  returning id into v_id;
  return v_id;
end;
$$;

-- Lista (o funcionário não recebe fornecedor nem os detalhes/motivos do registro).
create or replace function public.list_receipts(p_limit integer default 100)
returns table (id uuid, num integer, created_at timestamptz, updated_at timestamptz, user_name text,
               ref text, supplier text, status text, items jsonb, log jsonb)
language plpgsql
stable
security definer
set search_path = public
as $$
declare me public.profiles;
begin
  me := public._require_active();
  return query
    select r.id, r.num, r.created_at, r.updated_at, r.user_name, r.ref,
           case when me.role = 'gerente' then r.supplier else ''::text end,
           r.status, r.items,
           case when me.role = 'gerente' then r.log
                else (select coalesce(jsonb_agg(e || jsonb_build_object('detail', '')), '[]'::jsonb)
                        from jsonb_array_elements(r.log) e) end
    from public.receipts r
    order by r.created_at desc
    limit least(greatest(coalesce(p_limit, 100), 1), 300);
end;
$$;

-- Gerente autoriza: as quantidades recebidas entram no estoque e ficam no histórico.
create or replace function public.approve_receipt(p_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me public.profiles;
  r  public.receipts;
  x  record;
begin
  me := public._require_manager();
  select * into r from public.receipts where id = p_id for update;
  if not found then
    raise exception 'Recebimento não encontrado.';
  end if;
  if r.status <> 'pendente' then
    raise exception 'Este recebimento não está aguardando autorização.';
  end if;
  for x in select * from jsonb_to_recordset(r.items) as t(part_id uuid, name text, received integer) where received > 0 loop
    update public.parts set stock = stock + x.received where id = x.part_id;
    if not found then
      raise exception 'A peça "%" não existe mais.', x.name;
    end if;
    insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role, origin)
    values (x.part_id, x.name, 'entrada', x.received, 'Recebimento #' || r.num, me.id, me.name, me.role, 'recebimento');
  end loop;
  update public.receipts
     set status = 'concluido', updated_at = clock_timestamp(),
         log = log || jsonb_build_array(jsonb_build_object('at', clock_timestamp(), 'by', me.name, 'action', 'autorizado', 'detail', ''))
   where id = p_id;
end;
$$;

-- Gerente edita (nota, fornecedor, quantidades). Se já estava concluído, o estoque acompanha a diferença.
create or replace function public.edit_receipt(p_id uuid, p_ref text, p_items jsonb, p_supplier text, p_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me     public.profiles;
  r      public.receipts;
  v_new  jsonb;
  v_stat text;
  d      record;
  v_stock integer;
begin
  me := public._require_manager();
  select * into r from public.receipts where id = p_id for update;
  if not found then
    raise exception 'Recebimento não encontrado.';
  end if;
  if r.status = 'excluido' then
    raise exception 'Recebimentos excluídos não podem ser editados.';
  end if;
  v_new := public._receipt_items(p_items);
  v_stat := r.status;

  if r.status in ('concluido', 'concluido_editado') then
    if btrim(coalesce(p_reason, '')) = '' then
      raise exception 'Informe o motivo da edição.';
    end if;
    for d in
      select part_id, max(name) as name, sum(new_q) - sum(old_q) as diff
        from (
          select part_id, name, received as new_q, 0 as old_q from jsonb_to_recordset(v_new) as n(part_id uuid, name text, received integer)
          union all
          select part_id, name, 0, received from jsonb_to_recordset(r.items) as o(part_id uuid, name text, received integer)
        ) u
       group by part_id
      having sum(new_q) - sum(old_q) <> 0
       order by part_id
    loop
      select stock into v_stock from public.parts where id = d.part_id for update;
      if not found then
        raise exception 'A peça "%" não existe mais.', d.name;
      end if;
      if v_stock + d.diff < 0 then
        raise exception 'Não dá para reduzir: o estoque de "%" é % e a redução é de %.', d.name, v_stock, -d.diff;
      end if;
      update public.parts set stock = stock + d.diff where id = d.part_id;
      insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role, origin)
      values (d.part_id, d.name, case when d.diff > 0 then 'entrada' else 'saida' end, abs(d.diff),
              'Edição do recebimento #' || r.num, me.id, me.name, me.role, 'recebimento');
    end loop;
    v_stat := 'concluido_editado';
  end if;

  update public.receipts
     set ref = btrim(coalesce(p_ref, '')), supplier = btrim(coalesce(p_supplier, '')),
         items = v_new, status = v_stat, updated_at = clock_timestamp(),
         log = log || jsonb_build_array(jsonb_build_object('at', clock_timestamp(), 'by', me.name,
                'action', 'editado', 'detail', btrim(coalesce(p_reason, ''))))
   where id = p_id;
end;
$$;

-- Gerente exclui (motivo obrigatório). Nada é apagado: fica "Excluído" no registro.
-- Se já tinha entrado no estoque, a mercadoria sai de volta.
create or replace function public.delete_receipt(p_id uuid, p_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me      public.profiles;
  r       public.receipts;
  x       record;
  v_stock integer;
begin
  me := public._require_manager();
  if btrim(coalesce(p_reason, '')) = '' then
    raise exception 'Informe o motivo da exclusão.';
  end if;
  select * into r from public.receipts where id = p_id for update;
  if not found then
    raise exception 'Recebimento não encontrado.';
  end if;
  if r.status = 'excluido' then
    raise exception 'Este recebimento já foi excluído.';
  end if;

  if r.status in ('concluido', 'concluido_editado') then
    for x in select * from jsonb_to_recordset(r.items) as t(part_id uuid, name text, received integer) where received > 0 order by part_id loop
      select stock into v_stock from public.parts where id = x.part_id for update;
      if not found then
        continue;  -- peça apagada depois; não há estoque a devolver
      end if;
      if v_stock < x.received then
        raise exception 'Não dá para excluir: o estoque de "%" é % e o recebimento tinha %.', x.name, v_stock, x.received;
      end if;
    end loop;
    for x in select * from jsonb_to_recordset(r.items) as t(part_id uuid, name text, received integer) where received > 0 loop
      update public.parts set stock = stock - x.received where id = x.part_id;
      if found then
        insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role, origin)
        values (x.part_id, x.name, 'saida', x.received, 'Exclusão do recebimento #' || r.num, me.id, me.name, me.role, 'recebimento');
      end if;
    end loop;
  end if;

  update public.receipts
     set status = 'excluido', updated_at = clock_timestamp(),
         log = log || jsonb_build_array(jsonb_build_object('at', clock_timestamp(), 'by', me.name,
                'action', 'excluído', 'detail', btrim(p_reason)))
   where id = p_id;
end;
$$;

-- o estorno do Histórico não mexe em recebimentos (isso é feito na aba Recebimento)
create or replace function public.reverse_movement(p_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me      public.profiles;
  m       public.movements;
  v_stock integer;
  v_name  text;
  v_type  text;
  v_new   uuid;
begin
  me := public._require_manager();
  select * into m from public.movements where id = p_id for update;
  if not found then
    raise exception 'Movimentação não encontrada.';
  end if;
  if m.origin = 'recebimento' then
    raise exception 'Esta entrada veio de um recebimento. Para corrigir, edite ou exclua o recebimento na aba Recebimento.';
  end if;
  if m.type = 'producao' then
    raise exception 'Montagens não podem ser estornadas aqui. Se preciso, registre uma entrada das peças.';
  end if;
  if m.reverts is not null then
    raise exception 'Isto já é um estorno e não pode ser estornado.';
  end if;
  if m.reverted_by is not null then
    raise exception 'Esta movimentação já foi estornada.';
  end if;

  select stock, name into v_stock, v_name from public.parts where id = m.part_id for update;
  if not found then
    raise exception 'A peça desta movimentação não existe mais.';
  end if;

  if m.type = 'entrada' then
    if v_stock < m.qty then
      raise exception 'Não dá para estornar: a entrada foi de % e só há % em estoque.', m.qty, v_stock;
    end if;
    update public.parts set stock = stock - m.qty where id = m.part_id;
    v_type := 'saida';
  else
    update public.parts set stock = stock + m.qty where id = m.part_id;
    v_type := 'entrada';
  end if;

  insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role, reverts, origin)
  values (m.part_id, v_name, v_type, m.qty,
          'Estorno do lançamento de ' || to_char(m.created_at at time zone 'America/Fortaleza', 'DD/MM HH24:MI'),
          me.id, me.name, me.role, m.id, 'estorno')
  returning id into v_new;
  update public.movements set reverted_by = v_new where id = m.id;
end;
$$;

