-- ---------- produto pronto: quantas unidades já montadas existem ----------
alter table public.products add column if not exists ready integer not null default 0 check (ready >= 0);

-- ---------- pedidos de clientes ----------
create table if not exists public.orders (
  id         uuid primary key default gen_random_uuid(),
  num        integer generated by default as identity,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  user_name  text not null default '',
  customer   text not null default '',       -- só o gerente vê
  ref        text not null default '',       -- referência / número do pedido do cliente
  status     text not null default 'aberto' check (status in ('aberto', 'concluido', 'cancelado')),
  items      jsonb not null default '[]'::jsonb,
  log        jsonb not null default '[]'::jsonb
);
alter table public.orders enable row level security;
revoke all on public.orders from authenticated, anon;   -- só pelas funções abaixo

-- uso interno: valida os itens do pedido e guarda uma "foto" do nome/código do produto
create or replace function public._order_items(p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  it     jsonb;
  v_prod public.products;
  v_qty  integer;
  v_out  jsonb := '[]'::jsonb;
  v_seen uuid[] := '{}';
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Inclua pelo menos um produto no pedido.';
  end if;
  for it in select * from jsonb_array_elements(p_items) loop
    select * into v_prod from public.products where id = (it ->> 'product_id')::uuid;
    if not found then
      raise exception 'Um dos produtos do pedido não existe mais.';
    end if;
    if v_prod.id = any (v_seen) then
      raise exception 'O produto "%" aparece duas vezes. Some as quantidades em uma linha só.', v_prod.name;
    end if;
    v_seen := v_seen || v_prod.id;
    v_qty := (it ->> 'qty')::integer;
    if v_qty is null or v_qty <= 0 then
      raise exception 'A quantidade de cada produto deve ser maior que zero.';
    end if;
    v_out := v_out || jsonb_build_object('product_id', v_prod.id, 'name', v_prod.name, 'code', v_prod.code, 'qty', v_qty);
  end loop;
  return v_out;
end;
$$;

create or replace function public.create_order(p_customer text, p_ref text, p_items jsonb)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  me   public.profiles;
  v_id uuid;
begin
  me := public._require_manager();
  insert into public.orders (user_name, customer, ref, items, log)
  values (me.name, btrim(coalesce(p_customer, '')), btrim(coalesce(p_ref, '')), public._order_items(p_items),
          jsonb_build_array(jsonb_build_object('at', clock_timestamp(), 'by', me.name, 'action', 'criado', 'detail', '')))
  returning id into v_id;
  return v_id;
end;
$$;

-- Funcionário vê o andamento, mas não o nome do cliente nem os detalhes do registro.
create or replace function public.list_orders(p_limit integer default 100)
returns table (id uuid, num integer, created_at timestamptz, updated_at timestamptz, user_name text,
               customer text, ref text, status text, items jsonb, log jsonb)
language plpgsql
stable
security definer
set search_path = public
as $$
declare me public.profiles;
begin
  me := public._require_active();
  return query
    select o.id, o.num, o.created_at, o.updated_at, o.user_name,
           case when me.role = 'gerente' then o.customer else ''::text end,
           o.ref, o.status, o.items,
           case when me.role = 'gerente' then o.log
                else (select coalesce(jsonb_agg(e || jsonb_build_object('detail', '')), '[]'::jsonb)
                        from jsonb_array_elements(o.log) e) end
      from public.orders o
     order by o.created_at desc
     limit least(greatest(coalesce(p_limit, 100), 1), 300);
end;
$$;

create or replace function public.edit_order(p_id uuid, p_customer text, p_ref text, p_items jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me public.profiles;
  o  public.orders;
begin
  me := public._require_manager();
  select * into o from public.orders where id = p_id for update;
  if not found then
    raise exception 'Pedido não encontrado.';
  end if;
  if o.status <> 'aberto' then
    raise exception 'Só pedidos em andamento podem ser editados.';
  end if;
  update public.orders
     set customer = btrim(coalesce(p_customer, '')), ref = btrim(coalesce(p_ref, '')),
         items = public._order_items(p_items), updated_at = clock_timestamp(),
         log = log || jsonb_build_array(jsonb_build_object('at', clock_timestamp(), 'by', me.name, 'action', 'editado', 'detail', ''))
   where id = p_id;
end;
$$;

-- Finalizar: dá baixa nos produtos prontos. Só finaliza se TODOS os itens estiverem montados.
create or replace function public.finish_order(p_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me      public.profiles;
  o       public.orders;
  x       record;
  v_short text := '';
begin
  me := public._require_manager();
  select * into o from public.orders where id = p_id for update;
  if not found then
    raise exception 'Pedido não encontrado.';
  end if;
  if o.status <> 'aberto' then
    raise exception 'Este pedido não está em andamento.';
  end if;

  perform 1 from public.products
   where id in (select (e ->> 'product_id')::uuid from jsonb_array_elements(o.items) e)
   order by id for update;

  for x in
    select (e ->> 'product_id')::uuid as product_id, e ->> 'name' as name, (e ->> 'qty')::integer as qty,
           coalesce(p.ready, 0) as ready, p.id is null as gone
      from jsonb_array_elements(o.items) e
      left join public.products p on p.id = (e ->> 'product_id')::uuid
  loop
    if x.gone then
      raise exception 'O produto "%" não existe mais. Edite o pedido.', x.name;
    end if;
    if x.ready < x.qty then
      v_short := v_short || case when v_short = '' then '' else '; ' end
                 || format('%s (precisa %s, prontos %s)', x.name, x.qty, x.ready);
    end if;
  end loop;
  if v_short <> '' then
    raise exception 'Ainda faltam produtos montados: %.', v_short;
  end if;

  for x in select (e ->> 'product_id')::uuid as product_id, (e ->> 'qty')::integer as qty from jsonb_array_elements(o.items) e loop
    update public.products set ready = ready - x.qty where id = x.product_id;
  end loop;

  update public.orders
     set status = 'concluido', updated_at = clock_timestamp(),
         log = log || jsonb_build_array(jsonb_build_object('at', clock_timestamp(), 'by', me.name, 'action', 'finalizado', 'detail', ''))
   where id = p_id;
end;
$$;

-- Cancelar (motivo obrigatório): nada é apagado, o pedido fica "Cancelado" no registro.
create or replace function public.cancel_order(p_id uuid, p_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me public.profiles;
  o  public.orders;
begin
  me := public._require_manager();
  if btrim(coalesce(p_reason, '')) = '' then
    raise exception 'Informe o motivo do cancelamento.';
  end if;
  select * into o from public.orders where id = p_id for update;
  if not found then
    raise exception 'Pedido não encontrado.';
  end if;
  if o.status <> 'aberto' then
    raise exception 'Só pedidos em andamento podem ser cancelados.';
  end if;
  update public.orders
     set status = 'cancelado', updated_at = clock_timestamp(),
         log = log || jsonb_build_array(jsonb_build_object('at', clock_timestamp(), 'by', me.name, 'action', 'cancelado', 'detail', btrim(p_reason)))
   where id = p_id;
end;
$$;

create or replace function public.apply_production(p_product uuid, p_qty integer)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me       public.profiles;
  v_pname  text;
  v_short  text := '';
  r        record;
begin
  me := public._require_active();
  if p_qty is null or p_qty <= 0 then
    raise exception 'Informe uma quantidade maior que zero.';
  end if;

  select name into v_pname from public.products where id = p_product;
  if not found then
    raise exception 'Produto não encontrado.';
  end if;
  if not exists (select 1 from public.bom where product_id = p_product) then
    raise exception 'Este produto não tem ficha técnica.';
  end if;

  -- trava as peças sempre na mesma ordem (evita travamento entre dois usuários)
  perform 1 from public.parts
   where id in (select part_id from public.bom where product_id = p_product)
   order by id for update;

  for r in
    select b.part_id, pa.name, pa.stock, b.qty * p_qty as need
      from public.bom b join public.parts pa on pa.id = b.part_id
     where b.product_id = p_product
     order by pa.name
  loop
    if r.stock < r.need then
      v_short := v_short || case when v_short = '' then '' else '; ' end
                 || format('%s (precisa %s, tem %s)', r.name, r.need, r.stock);
    end if;
  end loop;
  if v_short <> '' then
    raise exception 'Estoque insuficiente: %.', v_short;
  end if;

  for r in
    select b.part_id, pa.name, b.qty * p_qty as need
      from public.bom b join public.parts pa on pa.id = b.part_id
     where b.product_id = p_product
  loop
    update public.parts set stock = stock - r.need where id = r.part_id;
    insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role)
    values (r.part_id, r.name, 'producao', r.need,
            format('Montagem: %s× %s', p_qty, v_pname), me.id, me.name, me.role);
  end loop;

  -- o produto montado passa a existir como estoque de produto pronto
  update public.products set ready = ready + p_qty where id = p_product;
end;
$$;

create or replace function public.save_products(items jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  it      jsonb;
  v_id    uuid;
  v_name  text;
begin
  perform public._require_manager();
  if items is null or jsonb_typeof(items) <> 'array' then
    raise exception 'Dados inválidos.';
  end if;

  for it in select * from jsonb_array_elements(items) loop
    v_id   := (it ->> 'id')::uuid;
    v_name := btrim(coalesce(it ->> 'name', ''));
    if v_name = '' then
      raise exception 'Todo produto precisa de um nome.';
    end if;

    insert into public.products (id, code, name, category)
    values (v_id, btrim(coalesce(it ->> 'code', '')), v_name,
            coalesce(nullif(btrim(it ->> 'category'), ''), 'Sem categoria'))
    on conflict (id) do update
      set code = excluded.code, name = excluded.name, category = excluded.category;

    if jsonb_typeof(it -> 'guide') = 'array' then
      update public.products set guide = coalesce(
        (select jsonb_agg(to_jsonb(btrim(s))) from jsonb_array_elements_text(it -> 'guide') s where btrim(s) <> ''),
        '[]'::jsonb) where id = v_id;
    end if;

    if jsonb_typeof(it -> 'ready') = 'number' then
      if (it ->> 'ready')::numeric < 0 or (it ->> 'ready')::numeric <> trunc((it ->> 'ready')::numeric) then
        raise exception 'A quantidade de produtos prontos deve ser um número inteiro, a partir de zero.';
      end if;
      update public.products set ready = (it ->> 'ready')::integer where id = v_id;
    end if;

    if jsonb_typeof(it -> 'price') = 'number' then
      if (it ->> 'price')::numeric < 0 then
        raise exception 'O preço não pode ser negativo.';
      end if;
      insert into public.product_prices (product_id, price) values (v_id, round((it ->> 'price')::numeric, 2))
      on conflict (product_id) do update set price = excluded.price;
    end if;

    if jsonb_typeof(it -> 'bom') = 'array' then
      delete from public.bom where product_id = v_id;
      insert into public.bom (product_id, part_id, qty)
      select v_id, (b ->> 'partId')::uuid, sum((b ->> 'qty')::integer)
        from jsonb_array_elements(it -> 'bom') b
       group by (b ->> 'partId')::uuid;
    end if;
  end loop;
end;
$$;

