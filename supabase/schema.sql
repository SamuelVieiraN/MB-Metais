-- Gerente autoriza: as quantidades recebidas entram no estoque e ficam no histórico.
create or replace function public.approve_receipt(p_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me public.profiles;
  r  public.receipts;
  x  record;
begin
  me := public._require_manager();
  select * into r from public.receipts where id = p_id for update;
  if not found then
    raise exception 'Recebimento não encontrado.';
  end if;
  if r.status <> 'pendente' then
    raise exception 'Este recebimento não está aguardando autorização.';
  end if;
  for x in select * from jsonb_to_recordset(r.items) as t(part_id uuid, name text, received integer) where received > 0 loop
