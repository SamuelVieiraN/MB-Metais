create or replace function public.adjust_ready(p_product uuid, p_delta integer, p_note text default '', p_kind text default 'ajuste')
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me     public.profiles;
  v_name text;
  v_old  integer;
begin
  me := public._require_manager();
