-- Histórico: o funcionário recebe só tipo, peça, quantidade, data/hora e quem fez.
-- Observações (fornecedor, destinatário, valores digitados) só o gerente enxerga.
create or replace function public.list_movements(p_limit integer default 500)
returns table (id uuid, created_at timestamptz, part_id uuid, part_name text, type text,
               qty integer, note text, user_name text, user_role text,
               reverts uuid, reverted_by uuid, origin text)
language plpgsql
stable
security definer
set search_path = public
as $$
declare me public.profiles;
begin
  me := public._require_active();
  return query
    select m.id, m.created_at, m.part_id, m.part_name, m.type, m.qty,
           case when me.role = 'gerente' then m.note else ''::text end,
           m.user_name, m.user_role, m.reverts, m.reverted_by, m.origin
    from public.movements m
    order by m.created_at desc
    limit least(greatest(coalesce(p_limit, 500), 1), 1000);
end;
$$;

-- ---------- estorno (só gerente): desfaz uma entrada ou saída lançada por engano ----------
create or replace function public.reverse_movement(p_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me      public.profiles;
  m       public.movements;
  v_stock integer;
  v_name  text;
  v_type  text;
  v_new   uuid;
begin
  me := public._require_manager();
  select * into m from public.movements where id = p_id for update;
  if not found then
    raise exception 'Movimentação não encontrada.';
  end if;
  if m.origin = 'recebimento' then
    raise exception 'Esta entrada veio de um recebimento. Para corrigir, edite ou exclua o recebimento na aba Recebimento.';
  end if;
  if m.type = 'producao' then
    raise exception 'Montagens não podem ser estornadas aqui. Se preciso, registre uma entrada das peças.';
  end if;
  if m.reverts is not null then
    raise exception 'Isto já é um estorno e não pode ser estornado.';
  end if;
  if m.reverted_by is not null then
    raise exception 'Esta movimentação já foi estornada.';
  end if;

  select stock, name into v_stock, v_name from public.parts where id = m.part_id for update;
  if not found then
    raise exception 'A peça desta movimentação não existe mais.';
  end if;

  if m.type = 'entrada' then
    if v_stock < m.qty then
      raise exception 'Não dá para estornar: a entrada foi de % e só há % em estoque.', m.qty, v_stock;
    end if;
    update public.parts set stock = stock - m.qty where id = m.part_id;
    v_type := 'saida';
  else
    update public.parts set stock = stock + m.qty where id = m.part_id;
    v_type := 'entrada';
  end if;

  insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role, reverts, origin)
  values (m.part_id, v_name, v_type, m.qty,
          'Estorno do lançamento de ' || to_char(m.created_at at time zone 'America/Fortaleza', 'DD/MM HH24:MI'),
          me.id, me.name, me.role, m.id, 'estorno')
  returning id into v_new;
  update public.movements set reverted_by = v_new where id = m.id;
end;
$$;

-- ---------- conferência: qualquer usuário envia a contagem; o gerente aprova ----------
create or replace function public.submit_count(p_items jsonb, p_note text default '')
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  me     public.profiles;
  it     jsonb;
  v_part public.parts;
  v_cnt  integer;
  v_out  jsonb := '[]'::jsonb;
  v_id   uuid;
begin
  me := public._require_active();
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Conte pelo menos uma peça.';
  end if;
  for it in select * from jsonb_array_elements(p_items) loop
    v_cnt := (it ->> 'counted')::integer;
    if v_cnt is null or v_cnt < 0 then
      raise exception 'A quantidade contada não pode ser negativa.';
    end if;
    select * into v_part from public.parts where id = (it ->> 'part_id')::uuid;
    if not found then
      raise exception 'Uma das peças contadas não existe mais.';
    end if;
    v_out := v_out || jsonb_build_object(
      'part_id', v_part.id, 'name', v_part.name, 'code', v_part.code,
      'system', v_part.stock, 'counted', v_cnt);
  end loop;
  insert into public.counts (user_id, user_name, note, items)
  values (me.id, me.name, coalesce(p_note, ''), v_out)
  returning id into v_id;
  return v_id;
end;
$$;

create or replace function public.list_counts(p_limit integer default 30)
returns table (id uuid, created_at timestamptz, user_name text, note text, status text,
               items jsonb, reviewed_by_name text, reviewed_at timestamptz)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  perform public._require_active();
  return query
    select c.id, c.created_at, c.user_name, c.note, c.status, c.items, c.reviewed_by_name, c.reviewed_at
    from public.counts c
    order by c.created_at desc
    limit least(greatest(coalesce(p_limit, 30), 1), 100);
end;
$$;

create or replace function public.review_count(p_id uuid, p_approve boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me     public.profiles;
  c      public.counts;
  it     jsonb;
  v_part public.parts;
  v_cnt  integer;
  v_diff integer;
begin
  me := public._require_manager();
  select * into c from public.counts where id = p_id for update;
  if not found then
    raise exception 'Contagem não encontrada.';
  end if;
  if c.status <> 'pendente' then
    raise exception 'Esta contagem já foi %.', c.status;
  end if;

  if p_approve then
    for it in select * from jsonb_array_elements(c.items) loop
      v_cnt := (it ->> 'counted')::integer;
      select * into v_part from public.parts where id = (it ->> 'part_id')::uuid for update;
      if not found then
        continue;  -- peça apagada depois da contagem
      end if;
      v_diff := v_cnt - v_part.stock;
      if v_diff <> 0 then
        update public.parts set stock = v_cnt where id = v_part.id;
        insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role, origin)
        values (v_part.id, v_part.name, case when v_diff > 0 then 'entrada' else 'saida' end, abs(v_diff),
                'Conferência de estoque (contagem de ' || c.user_name || ')',
                me.id, me.name, me.role, 'conferencia');
      end if;
    end loop;
  end if;

  update public.counts
     set status = case when p_approve then 'aprovada' else 'rejeitada' end,
         reviewed_by_name = me.name, reviewed_at = clock_timestamp()
   where id = p_id;
end;
$$;

-- Entrada ou saída de uma peça.
create or replace function public.apply_movement(
  p_part      uuid,
  p_type      text,
  p_qty       integer,
  p_note      text default '',
  p_unit_cost numeric default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me       public.profiles;
  v_stock  integer;
  v_name   text;
  v_cost   numeric;
  v_new    numeric;
begin
  me := public._require_active();
  if p_qty is null or p_qty <= 0 then
    raise exception 'Informe uma quantidade maior que zero.';
  end if;
  if p_type not in ('entrada', 'saida') then
    raise exception 'Tipo de movimentação inválido.';
  end if;

  select stock, name into v_stock, v_name from public.parts where id = p_part for update;
  if not found then
    raise exception 'Peça não encontrada.';
  end if;

  if p_type = 'saida' then
    if v_stock < p_qty then
      raise exception 'Só há % em estoque; não dá para dar saída de %.', v_stock, p_qty;
    end if;
    update public.parts set stock = stock - p_qty where id = p_part;
  else
    -- só o gerente informa custo; vira média ponderada com o estoque atual
    if p_unit_cost is not null and me.role = 'gerente' then
      if p_unit_cost < 0 then
        raise exception 'O custo não pode ser negativo.';
      end if;
      select cost into v_cost from public.part_costs where part_id = p_part;
      if v_cost is null or v_cost = 0 then
        v_new := round(p_unit_cost, 2);
      else
        v_new := round((v_stock * v_cost + p_qty * p_unit_cost) / (v_stock + p_qty), 2);
      end if;
      insert into public.part_costs (part_id, cost) values (p_part, v_new)
      on conflict (part_id) do update set cost = excluded.cost;
    end if;
    update public.parts set stock = stock + p_qty where id = p_part;
  end if;

  insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role)
  values (p_part, v_name, p_type, p_qty, case when me.role = 'gerente' then coalesce(p_note, '') else '' end, me.id, me.name, me.role);
end;
$$;

-- Montagem: desconta todas as peças da ficha técnica de uma vez, ou não faz nada.
create or replace function public.apply_production(p_product uuid, p_qty integer)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me       public.profiles;
  v_pname  text;
  v_short  text := '';
  r        record;
begin
  me := public._require_active();
  if p_qty is null or p_qty <= 0 then
    raise exception 'Informe uma quantidade maior que zero.';
  end if;

  select name into v_pname from public.products where id = p_product;
  if not found then
    raise exception 'Produto não encontrado.';
  end if;
  if not exists (select 1 from public.bom where product_id = p_product) then
    raise exception 'Este produto não tem ficha técnica.';
  end if;

  -- trava as peças sempre na mesma ordem (evita travamento entre dois usuários)
  perform 1 from public.parts
   where id in (select part_id from public.bom where product_id = p_product)
   order by id for update;

  for r in
    select b.part_id, pa.name, pa.stock, b.qty * p_qty as need
      from public.bom b join public.parts pa on pa.id = b.part_id
     where b.product_id = p_product
     order by pa.name
  loop
    if r.stock < r.need then
      v_short := v_short || case when v_short = '' then '' else '; ' end
                 || format('%s (precisa %s, tem %s)', r.name, r.need, r.stock);
    end if;
  end loop;
  if v_short <> '' then
    raise exception 'Estoque insuficiente: %.', v_short;
  end if;

  for r in
    select b.part_id, pa.name, b.qty * p_qty as need
      from public.bom b join public.parts pa on pa.id = b.part_id
     where b.product_id = p_product
  loop
    update public.parts set stock = stock - r.need where id = r.part_id;
    insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role)
    values (r.part_id, r.name, 'producao', r.need,
            format('Montagem: %s× %s', p_qty, v_pname), me.id, me.name, me.role);
  end loop;
end;
$$;

-- Criar ou atualizar peças (gerente). items = lista de
-- { id, code, name, stock, min, cost }  ("cost" ausente ou nulo = não mexe no custo).
-- Se o estoque informado for diferente do atual, grava a diferença no histórico.
create or replace function public.save_parts(items jsonb, p_note text default 'Ajuste manual')
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me       public.profiles;
  it       jsonb;
  v_id     uuid;
  v_name   text;
  v_in     integer;   -- estoque informado (nulo = não informado)
  v_min_in integer;   -- mínimo informado (nulo = não informado)
  v_new    integer;
  v_old    integer;
begin
  me := public._require_manager();
  if items is null or jsonb_typeof(items) <> 'array' then
    raise exception 'Dados inválidos.';
  end if;

  for it in select * from jsonb_array_elements(items) loop
    v_id     := (it ->> 'id')::uuid;
    v_name   := btrim(coalesce(it ->> 'name', ''));
    v_in     := case when jsonb_typeof(it -> 'stock') = 'number' then (it ->> 'stock')::integer end;
    v_min_in := case when jsonb_typeof(it -> 'min') = 'number' then (it ->> 'min')::integer end;
    if v_name = '' then
      raise exception 'Toda peça precisa de um nome.';
    end if;
    if coalesce(v_in, 0) < 0 or coalesce(v_min_in, 0) < 0 then
      raise exception 'Estoque e mínimo não podem ser negativos.';
    end if;

    select stock into v_old from public.parts where id = v_id for update;
    if found then
      -- estoque ausente = não mexe (evita pisar numa movimentação feita por outra pessoa)
      v_new := coalesce(v_in, v_old);
      update public.parts
         set code  = btrim(coalesce(it ->> 'code', code)),
             name  = v_name,
             min   = coalesce(v_min_in, min),
             stock = v_new
       where id = v_id;
      if v_new <> v_old then
        insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role)
        values (v_id, v_name, case when v_new > v_old then 'entrada' else 'saida' end,
                abs(v_new - v_old), coalesce(p_note, ''), me.id, me.name, me.role);
      end if;
    else
      v_new := coalesce(v_in, 0);
      insert into public.parts (id, code, name, stock, min)
      values (v_id, btrim(coalesce(it ->> 'code', '')), v_name, v_new, coalesce(v_min_in, 0));
      if v_new > 0 then
        insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role)
        values (v_id, v_name, 'entrada', v_new,
                case when p_note is null or p_note = 'Ajuste manual' then 'Estoque inicial'
                     else 'Estoque inicial · ' || p_note end,
                me.id, me.name, me.role);
      end if;
    end if;

    if jsonb_typeof(it -> 'cost') = 'number' then
      if (it ->> 'cost')::numeric < 0 then
        raise exception 'O custo não pode ser negativo.';
      end if;
      insert into public.part_costs (part_id, cost) values (v_id, round((it ->> 'cost')::numeric, 2))
      on conflict (part_id) do update set cost = excluded.cost;
    end if;
  end loop;
end;
$$;

-- Criar ou atualizar produtos (gerente). items = lista de
-- { id, code, name, category, price, bom: [ { partId, qty } ] }
-- "price" nulo = não mexe no preço; "bom" ausente = não mexe na ficha técnica.
create or replace function public.save_products(items jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  it      jsonb;
  v_id    uuid;
  v_name  text;
begin
  perform public._require_manager();
  if items is null or jsonb_typeof(items) <> 'array' then
    raise exception 'Dados inválidos.';
  end if;

  for it in select * from jsonb_array_elements(items) loop
    v_id   := (it ->> 'id')::uuid;
    v_name := btrim(coalesce(it ->> 'name', ''));
    if v_name = '' then
      raise exception 'Todo produto precisa de um nome.';
    end if;

    insert into public.products (id, code, name, category)
    values (v_id, btrim(coalesce(it ->> 'code', '')), v_name,
            coalesce(nullif(btrim(it ->> 'category'), ''), 'Sem categoria'))
    on conflict (id) do update
      set code = excluded.code, name = excluded.name, category = excluded.category;

    if jsonb_typeof(it -> 'price') = 'number' then
      if (it ->> 'price')::numeric < 0 then
        raise exception 'O preço não pode ser negativo.';
      end if;
      insert into public.product_prices (product_id, price) values (v_id, round((it ->> 'price')::numeric, 2))
      on conflict (product_id) do update set price = excluded.price;
    end if;

    if jsonb_typeof(it -> 'bom') = 'array' then
      delete from public.bom where product_id = v_id;
      insert into public.bom (product_id, part_id, qty)
      select v_id, (b ->> 'partId')::uuid, sum((b ->> 'qty')::integer)
        from jsonb_array_elements(it -> 'bom') b
       group by (b ->> 'partId')::uuid;
    end if;
  end loop;
end;
$$;

-- Foto de peça ou produto (qualquer usuário ativo). p_url nulo remove a foto.
