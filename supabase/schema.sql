end;
$$;

-- Gerente edita (nota, fornecedor, quantidades). Se já estava concluído, o estoque acompanha a diferença.
create or replace function public.edit_receipt(p_id uuid, p_ref text, p_items jsonb, p_supplier text, p_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me     public.profiles;
  r      public.receipts;
  v_new  jsonb;
  v_stat text;
  d      record;
  v_stock integer;
begin
  me := public._require_manager();
  select * into r from public.receipts where id = p_id for update;
  if not found then
    raise exception 'Recebimento não encontrado.';
  end if;
  if r.status = 'excluido' then
    raise exception 'Recebimentos excluídos não podem ser editados.';
  end if;
  v_new := public._receipt_items(p_items);
  v_stat := r.status;

  if r.status in ('concluido', 'concluido_editado') then
    if btrim(coalesce(p_reason, '')) = '' then
      raise exception 'Informe o motivo da edição.';
    end if;
    for d in
      select part_id, max(name) as name, sum(new_q) - sum(old_q) as diff
        from (
          select part_id, name, received as new_q, 0 as old_q from jsonb_to_recordset(v_new) as n(part_id uuid, name text, received integer)
          union all
          select part_id, name, 0, received from jsonb_to_recordset(r.items) as o(part_id uuid, name text, received integer)
        ) u
       group by part_id
      having sum(new_q) - sum(old_q) <> 0
       order by part_id
    loop
      select stock into v_stock from public.parts where id = d.part_id for update;
      if not found then
        raise exception 'A peça "%" não existe mais.', d.name;
      end if;
      if v_stock + d.diff < 0 then
        raise exception 'Não dá para reduzir: o estoque de "%" é % e a redução é de %.', d.name, v_stock, -d.diff;
      end if;
      update public.parts set stock = stock + d.diff where id = d.part_id;
      insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role, origin)
      values (d.part_id, d.name, case when d.diff > 0 then 'entrada' else 'saida' end, abs(d.diff),
              'Edição do recebimento #' || r.num, me.id, me.name, me.role, 'recebimento');
    end loop;
    v_stat := 'concluido_editado';
  end if;

  update public.receipts
     set ref = btrim(coalesce(p_ref, '')), supplier = btrim(coalesce(p_supplier, '')),
         items = v_new, status = v_stat, updated_at = clock_timestamp(),
         log = log || jsonb_build_array(jsonb_build_object('at', clock_timestamp(), 'by', me.name,
                'action', 'editado', 'detail', btrim(coalesce(p_reason, ''))))
   where id = p_id;
end;
$$;

-- Gerente exclui (motivo obrigatório). Nada é apagado: fica "Excluído" no registro.
-- Se já tinha entrado no estoque, a mercadoria sai de volta.
create or replace function public.delete_receipt(p_id uuid, p_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me      public.profiles;
  r       public.receipts;
  x       record;
  v_stock integer;
begin
  me := public._require_manager();
  if btrim(coalesce(p_reason, '')) = '' then
    raise exception 'Informe o motivo da exclusão.';
  end if;
  select * into r from public.receipts where id = p_id for update;
  if not found then
    raise exception 'Recebimento não encontrado.';
  end if;
  if r.status = 'excluido' then
    raise exception 'Este recebimento já foi excluído.';
  end if;

  if r.status in ('concluido', 'concluido_editado') then
    for x in select * from jsonb_to_recordset(r.items) as t(part_id uuid, name text, received integer) where received > 0 order by part_id loop
      select stock into v_stock from public.parts where id = x.part_id for update;
      if not found then
        continue;  -- peça apagada depois; não há estoque a devolver
      end if;
      if v_stock < x.received then
        raise exception 'Não dá para excluir: o estoque de "%" é % e o recebimento tinha %.', x.name, v_stock, x.received;
      end if;
    end loop;
    for x in select * from jsonb_to_recordset(r.items) as t(part_id uuid, name text, received integer) where received > 0 loop
      update public.parts set stock = stock - x.received where id = x.part_id;
      if found then
        insert into public.movements (part_id, part_name, type, qty, note, user_id, user_name, user_role, origin)
        values (x.part_id, x.name, 'saida', x.received, 'Exclusão do recebimento #' || r.num, me.id, me.name, me.role, 'recebimento');
      end if;
    end loop;
  end if;

  update public.receipts
     set status = 'excluido', updated_at = clock_timestamp(),
         log = log || jsonb_build_array(jsonb_build_object('at', clock_timestamp(), 'by', me.name,
                'action', 'excluído', 'detail', btrim(p_reason)))
   where id = p_id;
end;
$$;

